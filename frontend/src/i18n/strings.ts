/** Base dictionaries + every content area (src/i18n/content/*) merged into one lookup per language. */
const merge = (base: Dict, l: Lang) => Object.assign({}, base, ...AREAS.map(a => a[l]))
export const DICTS: Record<Lang, Dict> = { en: merge({ ...en, ...en2 }, 'en'), te: merge({ ...te, ...te2 }, 'te'), hi: merge({ ...hi, ...hi2 }, 'hi') }

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>) {
  let s = DICTS[lang][key] ?? DICTS.en[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}
